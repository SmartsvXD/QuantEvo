from src.optimization.repair import PortfolioConstraints


class ValidPortfolioSampling(Sampling):
    def __init__(self, n_evaluations: int, constraints: PortfolioConstraints) -> None:
        super().__init__()
        self.n_evaluations = n_evaluations
        self.constraints = constraints

    def _do(self, problem: Problem, n_samples: int, **kwargs) -> np.ndarray:
        # Sample random weights and project them onto the feasible simplex
        X = []
        for _ in range(n_samples):
            weights = np.random.rand(self.n_evaluations)
            weights = self._apply_constraints(weights)
            X.append(weights)
        return np.array(X)

    def _apply_constraints(self, weights: np.ndarray) -> np.ndarray:
        return self.constraints.apply(weights)


class PortfolioRepair(Repair):
    def __init__(self, constraints: PortfolioConstraints) -> None:
        super().__init__()
        self.constraints = constraints

    def _do(self, problem: Problem, X: np.ndarray, **kwargs) -> np.ndarray:
        # Repair infeasible portfolios generated by crossover or mutation
        X_repaired = []
        for ind in X:
            ind_repaired = self._apply_constraints(ind)
            X_repaired.append(ind_repaired)
        return np.array(X_repaired)

    def _apply_constraints(self, weights: np.ndarray) -> np.ndarray:
        return self.constraints.apply(weights)


class PortfolioProblem(Problem):
    def __init__(
        self,
        historical_stats: SampleStatistics,
        n_evaluations: int,
        evaluator: MetricSuite,
        constraints_evaluator: MetricSuite | None = None,
    ) -> None:
        n_constraints = constraints_evaluator.num_metrics if constraints_evaluator is not None else 0

        super().__init__(n_var=n_evaluations, n_constr=n_constraints, n_obj=evaluator.num_metrics, xl=0.0, xu=1.0)

        self.constraints_evaluator = constraints_evaluator
        self.historical_stats = historical_stats
        self.evaluator = evaluator

    def _evaluate(self, X: np.ndarray, out: dict, *args, **kwargs) -> None:
        out["F"] = self.evaluator.evaluate(X, self.historical_stats)

        if self.constraints_evaluator is not None:
            out["G"] = self.constraints_evaluator.evaluate(X, self.historical_stats)
        else:
            out["G"] = np.zeros((X.shape[0], self.n_constr))


class EarlyStoppingCallback(Callback):
    """
    Stops genetic algorithm if there are no significant improvements
    in Pareto front for a specified number of generations.
    """

    def __init__(
        self,
        patience: int = 30,
        min_improvement: float = 1e-4,
        verbose: bool = False,
        ref_point: np.ndarray | None = None,
    ) -> None:
        """
        :param patience: Number of generations without improvement before stopping.
        :param min_improvement: Minimum improvement required to reset the counter.
        :param verbose: If True, prints convergence information.
        """
        super().__init__()
        self.patience = patience
        self.min_improvement = min_improvement
        self.verbose = verbose
        self.ref_point = None if ref_point is None else np.asarray(ref_point, dtype=np.float64)
        self.counter = 0
        self.best_hv = None  # Hypervolume of the best front found
        self.generation = 0
        self._hv_indicator = None

    def notify(self, algorithm) -> None:
        self.generation += 1

        if algorithm.pop is not None and len(algorithm.pop) > 0:
            cv = algorithm.pop.get("CV")
            F = algorithm.pop.get("F")

            # Consider only individuals that satisfy G <= 0
            if cv is not None:
                feasible = np.all(cv <= 1e-6, axis=1)
                F = F[feasible]

            # If there is no feasible portfolio yet, wait for next generations
            if F is None or len(F) == 0:
                if self.verbose and self.generation % 10 == 0:
                    print(f"Gen {self.generation}: Population still infeasible...")
                return

            F = np.asarray(F, dtype=np.float64)

            # Dynamically initialize hypervolume reference point if not provided
            if self.ref_point is None:
                max_f = np.max(F, axis=0)
                self.ref_point = max_f + 0.1 * np.maximum(np.abs(max_f), 1.0)
                self._hv_indicator = HV(ref_point=self.ref_point)
            elif self._hv_indicator is None:
                self._hv_indicator = HV(ref_point=self.ref_point)

            current_hv = float(self._hv_indicator(F))

            if self.best_hv is None:
                self.best_hv = current_hv
                if self.verbose:
                    print(f"Gen {self.generation}: First valid population! HV = {current_hv:.6f}")
            else:
                improvement = current_hv - self.best_hv
                if improvement > self.min_improvement:
                    self.best_hv = current_hv
                    self.counter = 0
                    if self.verbose:
                        print(f"Gen {self.generation}: HV improvement {improvement:.6f}, hv = {current_hv:.6f}")
                else:
                    self.counter += 1
                    if self.verbose and self.counter % 10 == 0:
                        print(f"Gen {self.generation}: No improvement for {self.counter} gen")

                    if self.counter >= self.patience:
                        if self.verbose:
                            print(f"\nEarly stopping at generation {self.generation}")
                        algorithm.termination.force_termination = True
